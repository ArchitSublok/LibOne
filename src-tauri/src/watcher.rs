/// Check if a path should be ignored by the file watcher.
pub fn should_ignore_path(path: &Path, root_path: &Path, app_data_dir: Option<&Path>) -> bool {
    // 1. Must be inside root
    if !path.starts_with(root_path) {
        return true;
    }

    // 2. Check each path component against excluded directory names
    for component in path.components() {
        let name = component.as_os_str().to_string_lossy();
        if is_excluded_dir_name(&name) {
            return true;
        }
    }

    // 3. Ignore temp and lock files generated by office suites or text editors
    if let Some(file_name) = path.file_name().and_then(|n| n.to_str()) {
        if file_name.starts_with("~$")
            || file_name.starts_with(".~lock")
            || file_name.ends_with(".tmp")
            || file_name.ends_with(".crswap")
            || file_name.ends_with(".swp")
        {
            return true;
        }
    }

    // 4. Must not be inside LibOne's own AppData directory
    if let Some(app_data) = app_data_dir {
        if path.starts_with(app_data) {
            return true;
        }
    }

    // 5. Ignore symlinks outside selected root
    if path.is_symlink() {
        return true;
    }

    false
}

fn now_iso() -> String {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default();
    chrono::DateTime::<chrono::Utc>::from(UNIX_EPOCH + now).to_rfc3339()
}

/// Handle representing an active file-system watcher for a single scan root.
struct RootWatcherHandle {
    _watcher: RecommendedWatcher,
    stop_tx: Sender<()>,
    worker_handle: Option<JoinHandle<()>>,
}

/// Central manager orchestrating live file-system watchers across all enabled scan roots.
pub struct WatcherManager {
    watchers: HashMap<i64, RootWatcherHandle>,
    statuses: HashMap<i64, WatcherRootStatus>,
    is_refreshing: Arc<AtomicBool>,
    is_coalescing: Arc<AtomicBool>,
    last_refreshed_at: Option<String>,
}

impl Default for WatcherManager {
    fn default() -> Self {
        Self::new()
    }
}

impl WatcherManager {
    pub fn new() -> Self {
        Self {
            watchers: HashMap::new(),
            statuses: HashMap::new(),
            is_refreshing: Arc::new(AtomicBool::new(false)),
            is_coalescing: Arc::new(AtomicBool::new(false)),
            last_refreshed_at: None,
        }
    }

    /// Retrieve the overall status of all file-system watchers.
    pub fn get_overall_status(&self) -> WatcherOverallStatus {
        let active_count = self.statuses.values().filter(|s| s.active).count();
        WatcherOverallStatus {
            is_watching: active_count > 0,
            watched_roots_count: active_count,
            is_coalescing: self.is_coalescing.load(Ordering::Relaxed),
            is_refreshing: self.is_refreshing.load(Ordering::Relaxed),
            last_refreshed_at: self.last_refreshed_at.clone(),
            root_statuses: self.statuses.values().cloned().collect(),
        }
    }

    /// Start watching a single scan root if enabled.
    pub fn start_watching_root(&mut self, root: &ScanRoot, db: Database, app_handle: AppHandle) {
        let root_id = root.id;
        let root_path_str = root.absolute_path.clone();
        let root_path = PathBuf::from(&root_path_str);

        // Stop existing watcher for this root if already active
        self.stop_watching_root(root_id);

        if !root.enabled {
            self.statuses.insert(
                root_id,
                WatcherRootStatus {
                    root_id,
                    path: root_path_str,
                    active: false,
                    last_event_at: None,
                    error_message: None,
                },
            );
            return;
        }

        if !root_path.exists() || !root_path.is_dir() {
            self.statuses.insert(
                root_id,
                WatcherRootStatus {
                    root_id,
                    path: root_path_str,
                    active: false,
                    last_event_at: None,
                    error_message: Some("Directory does not exist on disk".into()),
                },
            );
            return;
        }

        let (notify_tx, notify_rx) = channel();
        let (stop_tx, stop_rx) = channel();

        let mut watcher = match RecommendedWatcher::new(
            move |res| {
                let _ = notify_tx.send(res);
            },
            Config::default(),
        ) {
            Ok(w) => w,
            Err(e) => {
                let err_msg = format!("Failed to initialize watcher: {e}");
                self.statuses.insert(
                    root_id,
                    WatcherRootStatus {
                        root_id,
                        path: root_path_str,
                        active: false,
                        last_event_at: None,
                        error_message: Some(err_msg),
                    },
                );
                return;
            }
        };

        if let Err(e) = watcher.watch(&root_path, RecursiveMode::Recursive) {
            let err_msg = format!("Failed to watch folder '{root_path_str}': {e}");
            self.statuses.insert(
                root_id,
                WatcherRootStatus {
                    root_id,
                    path: root_path_str,
                    active: false,
                    last_event_at: None,
                    error_message: Some(err_msg),
                },
            );
            return;
        }

        let app_data_dir: Option<PathBuf> = app_handle.path().app_data_dir().ok();
        let is_coalescing_clone = self.is_coalescing.clone();
        let is_refreshing_clone = self.is_refreshing.clone();
        let app_for_thread = app_handle.clone();
        let root_path_thread = root_path.clone();

        let worker_handle = thread::spawn(move || {
            run_coalescing_event_loop(
                root_id,
                root_path_thread,
                db,
                app_data_dir,
                app_for_thread,
                notify_rx,
                stop_rx,
                is_coalescing_clone,
                is_refreshing_clone,
            );
        });

        self.statuses.insert(
            root_id,
            WatcherRootStatus {
                root_id,
                path: root_path_str,
                active: true,
                last_event_at: None,
                error_message: None,
            },
        );

        self.watchers.insert(
            root_id,
            RootWatcherHandle {
                _watcher: watcher,
                stop_tx,
                worker_handle: Some(worker_handle),
            },
        );

        // Emit updated watcher status
        let _ = app_handle.emit("watcher-status", self.get_overall_status());
    }

    /// Stop watching a specific scan root.
    pub fn stop_watching_root(&mut self, root_id: i64) {
        if let Some(mut handle) = self.watchers.remove(&root_id) {
            let _ = handle.stop_tx.send(());
            if let Some(join) = handle.worker_handle.take() {
                let _ = join.join();
            }
        }
        if let Some(status) = self.statuses.get_mut(&root_id) {
            status.active = false;
        }
    }

    /// Stop all active scan root watchers.
    pub fn stop_all(&mut self) {
        for (_, mut handle) in self.watchers.drain() {
            let _ = handle.stop_tx.send(());
            if let Some(join) = handle.worker_handle.take() {
                let _ = join.join();
            }
        }
        for status in self.statuses.values_mut() {
            status.active = false;
        }
    }
}

impl Drop for WatcherManager {
    fn drop(&mut self) {
        self.stop_all();
    }
}

/// Background coalescing worker loop for a single scan root.
/// Collects bursts of raw filesystem notifications within a debounce window.
fn run_coalescing_event_loop(
    root_id: i64,
    root_path: PathBuf,
    db: Database,
    app_data_dir: Option<PathBuf>,
    app_handle: AppHandle,
    notify_rx: Receiver<Result<Event, notify::Error>>,
    stop_rx: Receiver<()>,
    is_coalescing: Arc<AtomicBool>,
    is_refreshing: Arc<AtomicBool>,
) {
    let quiet_duration = Duration::from_millis(500);
    let max_coalesce_duration = Duration::from_millis(2500);

    let mut pending_paths: HashSet<PathBuf> = HashSet::new();
    let mut fallback_to_rescan = false;
    let mut burst_start: Option<Instant> = None;

    loop {
        // 1. Check for stop signal
        if stop_rx.try_recv().is_ok() {
            break;
        }

        // 2. Wait for event with timeout if currently debouncing
        let timeout = if pending_paths.is_empty() {
            Duration::from_millis(200)
        } else {
            quiet_duration
        };

        match notify_rx.recv_timeout(timeout) {
            Ok(Ok(event)) => {
                let now = Instant::now();
                if burst_start.is_none() {
                    burst_start = Some(now);
                    is_coalescing.store(true, Ordering::Relaxed);
                    let _ = app_handle.emit("watcher-event", now_iso());
                }

                // If event cannot be interpreted safely or is an overflow/error, mark for rescan
                match event.kind {
                    EventKind::Other | EventKind::Any => {
                        fallback_to_rescan = true;
                    }
                    _ => {}
                }

                for path in event.paths {
                    if !should_ignore_path(&path, &root_path, app_data_dir.as_deref()) {
                        // If a directory was created/removed/renamed, rescan needed
                        if path.is_dir() {
                            fallback_to_rescan = true;
                        }
                        pending_paths.insert(path);
                    }
                }

                // If max coalesce window exceeded or path count > 50, trigger immediately
                let elapsed = burst_start.map(|s| s.elapsed()).unwrap_or_default();
                if elapsed >= max_coalesce_duration || pending_paths.len() > 50 {
                    trigger_refresh(
                        root_id,
                        &root_path,
                        &db,
                        &app_handle,
                        &pending_paths,
                        fallback_to_rescan || pending_paths.len() > 50,
                        &is_coalescing,
                        &is_refreshing,
                    );
                    pending_paths.clear();
                    fallback_to_rescan = false;
                    burst_start = None;
                }
            }
            Ok(Err(_err)) => {
                // Watcher error (e.g. buffer overflow): mark for rescan
                fallback_to_rescan = true;
            }
            Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
                // Quiet window elapsed: flush pending changes
                if !pending_paths.is_empty() {
                    trigger_refresh(
                        root_id,
                        &root_path,
                        &db,
                        &app_handle,
                        &pending_paths,
                        fallback_to_rescan,
                        &is_coalescing,
                        &is_refreshing,
                    );
                    pending_paths.clear();
                    fallback_to_rescan = false;
                    burst_start = None;
                }
            }
            Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
                break;
            }
        }
    }
}

/// Apply coalesced file changes or run targeted rescan.
fn trigger_refresh(
    root_id: i64,
    root_path: &Path,
    db: &Database,
    app_handle: &AppHandle,
    paths: &HashSet<PathBuf>,
    fallback_rescan: bool,
    is_coalescing: &Arc<AtomicBool>,
    is_refreshing: &Arc<AtomicBool>,
) {
    is_coalescing.store(false, Ordering::Relaxed);
    is_refreshing.store(true, Ordering::Relaxed);

    let folder_str = root_path.to_string_lossy().to_string();

    if fallback_rescan {
        // Fallback: execute targeted rescan for this scan root
        let app_data: Option<PathBuf> = app_handle.path().app_data_dir().ok();
        let _ = scanner::scan_folder_with_progress(
            db,
            root_id,
            &folder_str,
            app_data.as_deref(),
            None,
            None,
            |_| {},
        );
    } else {
        // Targeted incremental refresh for specific paths
        for path in paths {
            let norm = normalized_path(path);
            let target_exists = path.exists();

            if target_exists && path.is_file() {
                if let Ok(metadata) = path.metadata() {
                    let file_name = path
                        .file_name()
                        .map(|x| x.to_string_lossy().to_string())
                        .unwrap_or_default();
                    let extension = path
                        .extension()
                        .map(|x| x.to_string_lossy().to_lowercase())
                        .unwrap_or_default();
                    let size_bytes = metadata.len() as i64;
                    let modified_at = metadata.modified().ok().and_then(scanner::timestamp);
                    let created_at_if_available =
                        metadata.created().ok().and_then(scanner::timestamp);
                    let file_id = get_file_identity(path, &metadata);

                    let input = NewIndexedFile {
                        scan_root_id: root_id,
                        absolute_path: path.to_string_lossy().to_string(),
                        normalized_path: norm.clone(),
                        file_name,
                        extension,
                        size_bytes,
                        modified_at,
                        created_at_if_available,
                        content_hash_nullable: None,
                        file_id_nullable: file_id.clone(),
                        status: "indexed".into(),
                    };

                    match db.get_file_by_normalized_path(&norm) {
                        Ok(Some(existing)) => {
                            if existing.size_bytes != input.size_bytes
                                || existing.modified_at != input.modified_at
                            {
                                let mut updated = input;
                                updated.status = "changed".into();
                                let _ = db.update_indexed_file(existing.id, &updated);
                            } else {
                                let _ = db.touch_indexed_file(existing.id, "indexed");
                            }
                        }
                        Ok(None) => {
                            // Check if file identity matches a previously indexed file that was renamed
                            let mut moved = false;
                            if let Some(ref fid) = file_id {
                                if let Ok(root_files) = db.get_files_for_root(root_id) {
                                    if let Some(old) = root_files
                                        .iter()
                                        .find(|f| f.file_id_nullable.as_deref() == Some(fid))
                                    {
                                        if !Path::new(&old.absolute_path).exists() {
                                            let _ = db.move_indexed_file(old.id, &input);
                                            moved = true;
                                        }
                                    }
                                }
                            }
                            if !moved {
                                let _ = db.insert_indexed_file(&input);
                            }
                        }
                        Err(_) => {}
                    }
                }
            } else if !target_exists {
                // File deleted from disk: mark missing in database
                if let Ok(Some(existing)) = db.get_file_by_normalized_path(&norm) {
                    let _ = db.touch_indexed_file(existing.id, "missing");
                }
            }
        }
    }

    is_refreshing.store(false, Ordering::Relaxed);

    // Notify frontend of library updates
    let _ = app_handle.emit("library-updated", ());
    let _ = app_handle.emit("watcher-refreshed", now_iso());
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn temp_watch_dir(name: &str) -> PathBuf {
        let p = std::env::temp_dir().join(format!(
            "libone_watch_test_{}_{}_{}",
            name,
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let _ = fs::remove_dir_all(&p);
        fs::create_dir_all(&p).unwrap();
        p
    }

    #[test]
    fn test_should_ignore_path_exclusions() {
        let root = PathBuf::from("C:\\Users\\User\\Documents");

        // Allowed document
        let doc = root.join("Notes.pdf");
        assert!(!should_ignore_path(&doc, &root, None));

        // Path outside root
        let outside = PathBuf::from("C:\\Users\\User\\Downloads\\File.pdf");
        assert!(should_ignore_path(&outside, &root, None));

        // Excluded build / dependency folders
        let git_file = root.join(".git").join("HEAD");
        assert!(should_ignore_path(&git_file, &root, None));

        let node_modules_file = root.join("node_modules").join("package.json");
        assert!(should_ignore_path(&node_modules_file, &root, None));

        let target_file = root.join("target").join("debug").join("app.exe");
        assert!(should_ignore_path(&target_file, &root, None));

        // Temporary office files
        let office_temp = root.join("~$Document.docx");
        assert!(should_ignore_path(&office_temp, &root, None));

        let tmp_file = root.join("upload.tmp");
        assert!(should_ignore_path(&tmp_file, &root, None));

        // LibOne AppData folder
        let app_data = PathBuf::from("C:\\Users\\User\\AppData\\Roaming\\LibOne");
        let app_data_file = app_data.join("libone.db");
        assert!(should_ignore_path(&app_data_file, &root, Some(&app_data)));
    }

    #[test]
    fn test_targeted_refresh_create_modify_delete() {
        let dir = temp_watch_dir("refresh_test");
        let db_dir = temp_watch_dir("db_refresh_test");
        let db = Database::new(&db_dir).unwrap();

        let root = db
            .add_scan_root(dir.to_str().unwrap(), "Watch Root")
            .unwrap();
        let file_path = dir.join("article.txt");

        // 1. Create file
        fs::write(&file_path, b"Initial text").unwrap();
        let norm = normalized_path(&file_path);

        let mut paths = HashSet::new();
        paths.insert(file_path.clone());

        let coalescing = Arc::new(AtomicBool::new(false));
        let refreshing = Arc::new(AtomicBool::new(false));

        // Helper simulated targeted update (without needing AppHandle in pure unit test)
        let metadata = file_path.metadata().unwrap();
        let input = NewIndexedFile {
            scan_root_id: root.id,
            absolute_path: file_path.to_str().unwrap().to_string(),
            normalized_path: norm.clone(),
            file_name: "article.txt".into(),
            extension: "txt".into(),
            size_bytes: metadata.len() as i64,
            modified_at: metadata.modified().ok().and_then(scanner::timestamp),
            created_at_if_available: None,
            content_hash_nullable: None,
            file_id_nullable: None,
            status: "indexed".into(),
        };
        let indexed = db.insert_indexed_file(&input).unwrap();
        assert_eq!(indexed.status, "indexed");

        // 2. Modify file
        fs::write(&file_path, b"Updated content with more bytes").unwrap();
        let meta_mod = file_path.metadata().unwrap();
        let mut mod_input = input.clone();
        mod_input.size_bytes = meta_mod.len() as i64;
        mod_input.status = "changed".into();
        db.update_indexed_file(indexed.id, &mod_input).unwrap();

        let updated = db.get_indexed_file(indexed.id).unwrap().unwrap();
        assert_eq!(updated.status, "changed");
        assert_eq!(updated.size_bytes, meta_mod.len() as i64);

        // 3. Delete file
        fs::remove_file(&file_path).unwrap();
        assert!(!file_path.exists());
        db.touch_indexed_file(indexed.id, "missing").unwrap();

        let missing = db.get_indexed_file(indexed.id).unwrap().unwrap();
        assert_eq!(missing.status, "missing");

        let _ = fs::remove_dir_all(&dir);
        let _ = fs::remove_dir_all(&db_dir);
    }
}
