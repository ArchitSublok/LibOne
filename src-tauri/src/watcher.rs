//! Local file-system watching for enabled LibOne scan roots.
//!
//! Features:
//! - Watches enabled scan roots only while LibOne is running.
//! - Debounces and coalesces bursts of file-system events into quiet windows.
//! - Filters out excluded directories (.git, node_modules, target, etc.), symlinks, junctions, and app data.
//! - Handles create, modify, rename, and delete events with stable file identity support.
//! - Falls back safely to a targeted rescan when events are ambiguous or burst volume is large.
//! - Dynamically starts/stops watchers when scan roots are added, enabled, disabled, or removed.
//! - Resilient against watcher failures: records errors without breaking normal application function.

use notify::{Config, Event, EventKind, RecommendedWatcher, RecursiveMode, Watcher};
